#!/usr/bin/env python3
"""Generate mobile anthropometry references and backend decision fixtures."""
import argparse
import ast
import hashlib
import math
from datetime import date, datetime
from enum import Enum
from pathlib import Path

PACKAGE = "ar.com.ingenieriaalimentacion.domain.usecase.measurement"
ROOT = Path(__file__).resolve().parents[1]
KOTLIN = "kotlin/ar/com/ingenieriaalimentacion/domain/usecase/measurement"
Sex = Enum("Sex", {"MALE": "male", "FEMALE": "female"}, type=str)
AlertType = Enum("AlertType", {s.upper(): s for s in (
    "severely_wasted", "wasted", "overweight", "obese",
    "severe_underweight", "underweight",
)}, type=str)
AlertSeverity = Enum("AlertSeverity", {
    "CRITICAL": "critical", "HIGH": "high", "MEDIUM": "medium",
}, type=str)


def number(value):
    value = float(value)
    if not math.isfinite(value):
        raise ValueError("Nonfinite reference or fixture value")
    return repr(value)


def header(digest):
    return (f"package {PACKAGE}\n\n"
            "import ar.com.ingenieriaalimentacion.domain.model.subject.Sex\n\n"
            "// Generated by scripts/generate_anthropometry_reference.py; do not edit.\n"
            f"// Backend classifier + reference SHA256: {digest}\n")


def generate(backend):
    ref_path = backend / "app/reference_data/who_bmi_for_age.py"
    rule_path = backend / "app/reference_data/anthropometry.py"
    source = ref_path.read_bytes() + b"\n" + rule_path.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    ref_ast = ast.parse(ref_path.read_text())
    table_node = next(n for n in ref_ast.body if isinstance(n, ast.AnnAssign)
                      and isinstance(n.target, ast.Name)
                      and n.target.id == "WHO_BMI_LMS")
    table = ast.literal_eval(table_node.value)
    assert set(table) == {(s.value, m) for s in Sex for m in range(229)}
    for triple in table.values():
        assert len(triple) == 3
        for value in triple:
            number(value)
    rules = ast.parse(rule_path.read_text())
    rules.body = [n for n in rules.body
                  if not isinstance(n, (ast.Import, ast.ImportFrom))]
    namespace = dict(math=math, date=date, datetime=datetime,
                     Sex=Sex, AlertType=AlertType, AlertSeverity=AlertSeverity,
                     WHO_BMI_LMS=table)
    exec(compile(rules, str(rule_path), "exec"), namespace)
    evaluate = namespace["evaluate_alerts"]
    assert namespace["MAX_CHILD_AGE_MONTHS"] == 228

    lines = [header(digest), "internal object WhoBmiLms {",
             "    data class Lms(val lambda: Double, val median: Double, val sigma: Double)",
             "    private val bySex = mapOf("]
    for sex in Sex:
        kotlin_sex = "Male" if sex == Sex.MALE else "Female"
        lines.append(f"        Sex.{kotlin_sex} to listOf(")
        for month in range(229):
            values = ", ".join(number(v) for v in table[(sex.value, month)])
            lines.append(f"            Lms({values}), // month {month}")
        lines.append("        ),")
    lines += ["    )", "    fun get(sex: Sex, months: Int): Lms? =",
              "        bySex[sex]?.getOrNull(months)", "}", ""]
    reference = "\n".join(lines)

    rows = []
    measured = date(2024, 1, 15)
    for sex in Sex:
        for month in range(229):
            absolute = measured.year * 12 + measured.month - 1 - month
            year, month_index = divmod(absolute, 12)
            birth = date(year, month_index + 1, 15)
            lam, median, sigma = table[(sex.value, month)]
            values = {10.0, 16.0, 20.0, 30.0}
            # Stay away from floating-point ambiguity at inverse-derived cutoffs.
            # Exact strict/inclusive comparisons get separate direct unit tests.
            for z0 in (-3.0, -2.0, 2.0, 3.0):
                for z in (z0 - 1e-6, z0 + 1e-6):
                    base = 1 + lam * sigma * z
                    if abs(lam) < 1e-10:
                        values.add(median * math.exp(sigma * z))
                    elif base > 0:
                        values.add(median * base ** (1 / lam))
            for bmi in sorted(values):
                required = bool(evaluate(bmi, sex, birth, datetime(2024, 1, 15)))
                rows.append((sex, birth, measured, bmi, required))
    for sex in Sex:
        for bmi in (15.999999, 16.0, 18.499999, 18.5, 24.999999, 25.0,
                    29.999999, 30.0):
            required = bool(evaluate(bmi, sex, date(1990, 1, 15),
                                     datetime(2024, 1, 15)))
            rows.append((sex, date(1990, 1, 15), measured, bmi, required))
    cases = [header(digest),
             "internal data class AnthropometryParityCase(",
             "    val sex: Sex, val birthDate: String, val measuredDate: String,",
             "    val bmi: Double, val requiresConfirmation: Boolean,", ")"]
    groups = [rows[i:i+100] for i in range(0, len(rows), 100)]
    cases.append("internal val anthropometryParityCases = listOf(")
    cases += [f"    cases{i}()," for i in range(len(groups))]
    cases.append(").flatten()")
    for i, group in enumerate(groups):
        cases.append(f"private fun cases{i}() = listOf(")
        for sex, birth, measured_date, bmi, required in group:
            kotlin_sex = "Male" if sex == Sex.MALE else "Female"
            cases.append(f'    AnthropometryParityCase(Sex.{kotlin_sex}, '
                         f'"{birth}", "{measured_date}", {number(bmi)}, '
                         f'{str(required).lower()}),')
        cases.append(")")
    cases.append("")
    return {
        ROOT / "composeApp/src/commonMain" / KOTLIN / "WhoBmiLms.kt": reference,
        ROOT / "composeApp/src/commonTest" / KOTLIN / "AnthropometryParityCases.kt":
            "\n".join(cases),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--backend", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate(args.backend.resolve())
    for path, expected in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"Generated reference differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
